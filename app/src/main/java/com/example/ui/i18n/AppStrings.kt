fun stringsForLanguage(code: String): AppStrings = when (code) {
    "en" -> EnglishStrings
    "it" -> ItalianStrings
    else -> RussianStrings
}

fun filterDisplayLabel(canonicalKey: String, strings: AppStrings): String = when (canonicalKey) {
    "Все" -> strings.filterAll
    "Хип-хоп" -> strings.filterHipHop
    "Электроника" -> strings.filterElectronic
    "Поп" -> strings.filterPop
    "Рок" -> strings.filterRock
    "Lo-Fi" -> strings.filterLoFi
    "Синтвейв" -> strings.filterSynthwave
    "Амбиент" -> strings.filterAmbient
    "Инди" -> strings.filterIndie
    "Мои треки" -> strings.filterMyTracks
    else -> canonicalKey
}

